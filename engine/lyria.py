"""Music generation with Lyria (Gemini API) — the in-house replacement for Suno.

Two models, same endpoint:
    lyria-3-clip-preview  always exactly 30s   → auditioning prompts, beds under a hook
    lyria-3.5             a couple of minutes  → full songs with verses/chorus/bridge

Vocals and lyrics are generated BY DEFAULT; ask for instrumental explicitly when you want a
bed under a voice-over. Up to 10 images can ride along with the text prompt, so a frame from
the creative can drive the music. Output is 44.1 kHz stereo MP3 (WAV optional on 3.5) and
every file carries an inaudible SynthID watermark.

Auth reuses the SAME Gemini key the caption polish pass uses (GEMINI_API_KEY), so there's no
new credential to hand out. Nothing is hardcoded and nothing is committed.

Docs: https://ai.google.dev/gemini-api/docs/music-generation
"""
import os
import re
import json
import base64

API_BASE = os.environ.get("CS_GEMINI_BASE", "https://generativelanguage.googleapis.com/v1beta")
INTERACTIONS_URL = API_BASE + "/interactions"

MODELS = {
    "clip": os.environ.get("CS_LYRIA_CLIP", "lyria-3-clip-preview"),   # fixed 30 s
    "song": os.environ.get("CS_LYRIA_SONG", "lyria-3.5"),              # full length
}
MAX_IMAGES = 10
NO_VOCALS = "Instrumental only, no vocals."


def _key(api_key=None):
    api_key = api_key or os.environ.get("GEMINI_API_KEY")
    if not api_key:
        raise RuntimeError("Gemini API key missing (add it in ⚙ Settings, or GEMINI_API_KEY).")
    return api_key


def model_id(kind):
    return MODELS.get(kind or "clip", MODELS["clip"])


def build_input(prompt, instrumental=False, images=None, lyrics=""):
    """Text-only prompt, or a multimodal list when images are attached.

    Own lyrics are appended under a "Lyrics:" heading rather than mixed into the musical
    direction — the docs are explicit that instructions and lyrics should stay separated.
    Section tags ([Verse 1], [Chorus], [Bridge]) and (parentheses) for echo/backing vocals
    are passed through untouched. Ignored for instrumentals — there's nothing to sing.
    """
    text = (prompt or "").strip()
    words = (lyrics or "").strip()
    if instrumental:
        if "instrumental" not in text.lower():
            text = (text + " " + NO_VOCALS).strip()
    elif words:
        if not re.search(r"^\s*lyrics\s*:", words, re.I | re.M):
            words = "Lyrics:\n" + words
        text = (text + "\n\n" + words).strip()
    imgs = [i for i in (images or []) if i and i.get("data")][:MAX_IMAGES]
    if not imgs:
        return text
    out = [{"type": "text", "text": text}]
    for im in imgs:
        out.append({"type": "image",
                    "mime_type": im.get("mime_type") or "image/jpeg",
                    "data": im["data"]})
    return out


# ---------------------------------------------------------------- auto-prompt ---
# Writing a good Lyria brief is a skill (genre + era + instruments + BPM + key + structure +
# vocal profile). This turns "here are the lyrics, a couple of words and some style tablets"
# into three finished briefs to choose from. It writes the DIRECTION only — never the lyrics,
# which stay the user's, exactly like the caption polish pass never invents words.
AUTOPROMPT_MODEL = os.environ.get("CS_GEMINI_MODEL", "gemini-3.7-flash")
AUTOPROMPT_FALLBACKS = ("gemini-2.5-flash",)

_AP_SCHEMA = {
    "type": "object",
    "properties": {
        "options": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "title": {"type": "string"},
                    "prompt": {"type": "string"},
                    "notes": {"type": "string"},
                },
                "required": ["title", "prompt"],
            },
        }
    },
    "required": ["options"],
}

_AP_RULES = """You write briefs for the Lyria music model. Given lyrics, a short intent and
some chosen style tablets, produce THREE distinct musical directions.

Each `prompt` must read as one natural-language brief and should cover, in this order:
genre (and era if it helps), mood, tempo in BPM, key, the main instruments and how they
interact, the song structure, and — unless the track is instrumental — a specific singer
profile (gender, timbre, range, delivery).

Hard rules:
- NEVER include the lyrics, or any line of them, in the prompt. The lyrics are supplied
  separately. Do not paraphrase or rewrite them either.
- Respect every chosen style tablet. If two tablets conflict, follow the more specific one
  and say so in `notes`.
- Keep each prompt under 100 words. No bullet lists, no headings, no section tags.
- Make the three options genuinely different readings (not three rewordings of one idea).
- `title` is a 2–4 word handle for the option. `notes` is one short line about the call you
  made, in the language of the user's intent.
"""


def autoprompt(lyrics="", brief="", chips=None, kind="clip", instrumental=False,
               api_key=None, model=None, timeout=120):
    """Three candidate Lyria briefs. Returns {"options":[{title,prompt,notes}], "model": id}."""
    import requests  # lazy
    api_key = _key(api_key)
    chips = [c for c in (chips or []) if str(c).strip()]
    if not (lyrics or "").strip() and not (brief or "").strip() and not chips:
        raise RuntimeError("Дай хоч щось: текст пісні, кілька слів або таблетки стилю.")
    parts = [_AP_RULES, ""]
    parts.append(f"Target: {'a 30-second clip' if kind == 'clip' else 'a full song of a couple of minutes'}.")
    parts.append(f"Vocals: {'NO — instrumental only' if instrumental else 'yes, sung'}.")
    if brief.strip():
        parts.append("User intent: " + brief.strip())
    if chips:
        parts.append("Chosen style tablets: " + "; ".join(chips))
    if (lyrics or "").strip():
        parts.append("Lyrics (for MOOD and STRUCTURE only — never quote them):\n" + lyrics.strip()[:4000])
    prompt = "\n\n".join(parts)
    body = {"contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"responseMimeType": "application/json",
                                 "responseSchema": _AP_SCHEMA, "temperature": 0.9}}
    tried = []
    for m in [model or AUTOPROMPT_MODEL] + list(AUTOPROMPT_FALLBACKS):
        if m in tried:
            continue
        tried.append(m)
        r = requests.post(f"{API_BASE}/models/{m}:generateContent",
                          headers={"x-goog-api-key": api_key, "Content-Type": "application/json"},
                          json=body, timeout=timeout)
        if r.status_code == 404:
            continue
        if r.status_code >= 300:
            raise RuntimeError(f"Auto-prompt failed ({r.status_code}): {r.text[:300]}")
        data = r.json() or {}
        try:
            txt = data["candidates"][0]["content"]["parts"][0]["text"]
            out = json.loads(txt)
        except Exception:
            raise RuntimeError("Auto-prompt returned nothing usable.")
        opts = []
        for o in (out.get("options") or [])[:3]:
            p = str(o.get("prompt", "")).strip()
            if p:
                opts.append({"title": str(o.get("title", "")).strip()[:40] or "Варіант",
                             "prompt": p, "notes": str(o.get("notes", "")).strip()[:200]})
        if not opts:
            raise RuntimeError("Auto-prompt returned no options.")
        return {"options": opts, "model": m}
    raise RuntimeError("No Gemini model available on this key: " + ", ".join(tried))


def _extract(data):
    """Pull audio bytes + lyrics out of an Interactions response.

    Convenience properties first (output_audio / output_text), then the raw `steps` walk the
    docs describe — a music response interleaves text (lyrics / structure) and audio blocks.
    """
    audio_b64, mime, texts = None, "audio/mpeg", []
    oa = data.get("output_audio") or data.get("outputAudio")
    if isinstance(oa, dict) and oa.get("data"):
        audio_b64 = oa["data"]
        mime = oa.get("mime_type") or oa.get("mimeType") or mime
    ot = data.get("output_text") or data.get("outputText")
    if isinstance(ot, str) and ot.strip():
        texts.append(ot)
    if not audio_b64:
        for step in (data.get("steps") or []):
            if (step.get("type") or "") != "model_output":
                continue
            for block in (step.get("content") or []):
                bt = block.get("type")
                if bt == "audio" and block.get("data"):
                    audio_b64 = block["data"]
                    mime = block.get("mime_type") or block.get("mimeType") or mime
                elif bt == "text" and block.get("text"):
                    texts.append(block["text"])
    if not audio_b64:
        raise RuntimeError("Lyria returned no audio (prompt may have been blocked by safety filters).")
    return base64.b64decode(audio_b64), mime, "\n".join(t for t in texts if t).strip()


def generate(prompt, kind="clip", instrumental=False, images=None, api_key=None,
             wav=False, timeout=900, lyrics=""):
    """One track. Returns {"audio": bytes, "mime": str, "ext": str, "lyrics": str, "model": str}."""
    import requests  # lazy
    api_key = _key(api_key)
    if not (prompt or "").strip() and not (lyrics or "").strip() and not images:
        raise RuntimeError("Write a prompt first (genre, mood, BPM, instruments…).")
    m = model_id(kind)
    body = {"model": m, "input": build_input(prompt, instrumental, images, lyrics)}
    if wav and kind == "song":          # WAV is only offered on the full-length model
        body["response_format"] = {"type": "audio"}
    r = requests.post(INTERACTIONS_URL,
                      headers={"x-goog-api-key": api_key, "Content-Type": "application/json"},
                      json=body, timeout=timeout)
    if r.status_code >= 300:
        raise RuntimeError(f"Lyria failed ({r.status_code}): {r.text[:300]}")
    audio, mime, lyrics = _extract(r.json() or {})
    ext = ".wav" if "wav" in (mime or "") else ".mp3"
    return {"audio": audio, "mime": mime, "ext": ext, "lyrics": lyrics, "model": m}
